import { ApiError } from './reliability';
/** Additive API metadata. Legacy records are preserved; a book title is not verification. */
export type Source = {
  source_id: string; source_title: string | null; author: string | null; dynasty: string | null;
  edition: string | null; reference: string | null;
  content_type: 'original_text' | 'historical_annotation' | 'modern_research' | 'ai_interpretation';
  verification_status: 'unverified' | 'ai_generated'; content: string;
};
const optional = (v: unknown): string | null => typeof v === 'string' && v.trim() ? v.trim() : null;
export function normalizeAnnotation(ann: any, paragraphId: string) {
  // These prefixes are generated by ai_historical_annotator.py without ai_generated.
  const simulated = /^(guoxiang|chengxuanying|linxiyi|maozhuan|zhengjian|zhuxi-shijing)-(zhuangzi|shijing)-/.test(ann.id || '');
  const aiGenerated = ann.ai_generated === true || simulated || /^ai-/.test(ann.id || '') || /AI|人工智能/i.test(ann.author || '');
  const source: Source = {
    source_id: `${paragraphId}:annotation:${ann.id || 'unidentified'}`,
    source_title: optional(ann.source_title) || optional(ann.source), author: optional(ann.author),
    dynasty: optional(ann.dynasty) || optional(ann.era_name) || optional(ann.era),
    edition: optional(ann.edition), reference: optional(ann.reference),
    content_type: aiGenerated ? 'ai_interpretation' : ann.era === 'modern' ? 'modern_research' : 'historical_annotation',
    // No reviewed provenance registry exists yet. Never trust a legacy 'verified' flag.
    verification_status: aiGenerated ? 'ai_generated' : 'unverified', content: typeof ann.content === 'string' ? ann.content : '',
  };
  return { ...ann, ...source, paragraph_id: paragraphId, ai_generated: aiGenerated };
}
export function originalSource(para: any, chapter: any, classic: any): Source {
  return {
    source_id: `${para.id}:original`, source_title: optional(classic?.title), author: optional(classic?.author),
    dynasty: optional(classic?.dynasty), edition: optional(para.edition) || optional(classic?.edition),
    reference: optional(para.reference) || optional(chapter.reference), content_type: 'original_text',
    verification_status: 'unverified', content: para.content || '',
  };
}
async function loadParagraphData(bucket: R2Bucket, paragraphId: string) {
  if (!/^[a-z0-9_]+(?:-[a-z0-9_]+)+$/i.test(paragraphId) || paragraphId.length > 160) return null;
  const chapterId = paragraphId.split('-').slice(0, -1).join('-');
  const classicId = chapterId.split('-').slice(0, -1).join('-');
  const obj = await bucket.get(`content/${classicId}/${chapterId}.json`);
  if (!obj) return null;
  const chapter: any = await obj.json();
  const paragraph = (chapter.paragraphs || []).find((p: any) => p.id === paragraphId);
  if (!paragraph) return null;
  const catalog = await bucket.get('metadata/classics.json');
  const data: any = catalog ? await catalog.json() : {};
  const classic = (data.classics || []).find((b: any) => b.id === (chapter.classic_id || classicId));
  const annotations = (paragraph.annotations || []).map((a: any) => normalizeAnnotation(a, paragraphId));
  return { paragraph, chapter, classic, annotations, sources: [originalSource(paragraph, chapter, classic), ...annotations] as Source[] };
}

export async function loadParagraph(bucket: R2Bucket, paragraphId: string) {
  try { return await loadParagraphData(bucket,paragraphId); }
  catch (error) {
    if (error instanceof ApiError) throw error;
    if (error instanceof SyntaxError) throw new ApiError(500,'knowledge_data_invalid','馆藏数据格式异常，请凭请求编号联系维护人员。',null,{cause:error});
    throw new ApiError(503,'knowledge_unavailable','馆藏来源暂时无法读取，请稍后重试。',null,{cause:error});
  }
}
